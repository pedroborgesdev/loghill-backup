func seedSenders(ctx context.Context, repo repositories.SenderRepository, now time.Time) error {
	for index, seed := range senderSeeds() {
		lastSeen := now.Add(-seed.LastSeen)
		created := now.AddDate(0, 0, -(35 + index*3))
		status := domain.StatusOnline
		if seed.LastSeen > 5*time.Minute {
			status = domain.StatusInactive
		}
		sender := domain.Sender{ID: seed.ID, Name: seed.Name, Description: seed.Description, Status: status, CreatedAt: created, UpdatedAt: lastSeen, LastActivityAt: timePointer(lastSeen)}
		if status == domain.StatusInactive {
			sender.InactiveAt = timePointer(lastSeen.Add(5 * time.Minute))
		}
		if err := repo.Create(ctx, sender); err != nil {
			return fmt.Errorf("create sender %s: %w", seed.ID, err)
		}
		instanceID := fmt.Sprintf("ins_%032x", index+1)
		instance := domain.SenderInstance{ID: instanceID, CreatedAt: created.Add(2 * time.Minute), LastActivityAt: timePointer(lastSeen), LastHealthcheckAt: timePointer(lastSeen), Status: status}
		if err := repo.RegisterInstance(ctx, seed.ID, instance); err != nil {
			return fmt.Errorf("register instance for %s: %w", seed.ID, err)
		}
		entries := buildLogs(seed, instanceID, now, index)
		var count, size int64
		for _, entry := range entries {
			nextCount, nextSize, appendErr := repo.Append(ctx, seed.ID, entry, domain.NumberUnitValue{Value: 10_000, Unit: domain.StorageLines})
			if appendErr != nil {
				return fmt.Errorf("append log for %s: %w", seed.ID, appendErr)
			}
			count, size = nextCount, nextSize
		}
		sender.LogLineCount, sender.LogFileSize = count, size
		sender.InstanceCount = 1
		if updateErr := repo.Update(ctx, sender); updateErr != nil {
			return updateErr
		}
	}
	return nil
}

func buildLogs(seed senderSeed, instanceID string, now time.Time, senderIndex int) []domain.LogEntry {
	entries := make([]domain.LogEntry, 0, seed.LogCount)
	for index := 0; index < seed.LogCount; index++ {
		message := seed.Messages[index%len(seed.Messages)]
		age := seed.LastSeen + time.Duration(index*17+senderIndex*3)*time.Minute
		if index > seed.LogCount*2/3 {
			age += time.Duration(index%3) * 12 * time.Hour
		}
		timestamp := now.Add(-age)
		metadata := cloneMap(message.Metadata)
		metadata["environment"] = "production-demo"
		metadata["instance"] = fmt.Sprintf("%s-%02d", seed.ID, senderIndex+1)
		entries = append(entries, domain.LogEntry{Timestamp: timestamp, ActivityAt: timestamp, SenderID: seed.ID, InstanceID: instanceID, Severity: message.Severity, Message: message.Message, Event: message.Event, EventOccurrenceID: occurrence(message.Event, index), Metadata: metadata})
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].Timestamp.Before(entries[j].Timestamp) })
	return entries
}

