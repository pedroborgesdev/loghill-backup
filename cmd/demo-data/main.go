func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "populate demo data:", err)
		os.Exit(1)
	}
	fmt.Printf("LogHill demo data created in %s\n", demoDir)
}

func run() error {
	root, err := filepath.Abs(demoDir)
	if err != nil {
		return err
	}
	if filepath.Base(root) != "data" {
		return fmt.Errorf("refusing to replace unexpected directory %q", root)
	}
	marker := filepath.Join(root, demoMarker)
	if _, err = os.Stat(root); err == nil {
		if _, markerErr := os.Stat(marker); markerErr != nil {
			empty, checkErr := initialDataIsEmpty(root)
			if checkErr != nil {
				return checkErr
			}
			if !empty {
				return fmt.Errorf("%s contains application data and was not created by this command", demoDir)
			}
		} else {
			if err = os.RemoveAll(root); err != nil {
				return err
			}
		}
	} else if !errors.Is(err, os.ErrNotExist) {
		return err
	}
	if err = os.MkdirAll(root, 0o750); err != nil {
		return err
	}
	if err = os.WriteFile(marker, []byte("Generated by go run ./cmd/demo-data\n"), 0o640); err != nil {
		return err
	}

	now := time.Now().UTC().Truncate(time.Second)
	ctx := context.Background()
	repo := repositories.NewSenderRepository(root)
	if err = repo.Init(); err != nil {
		return err
	}
	if err = seedSenders(ctx, repo, now); err != nil {
		return err
	}
	if err = seedSettings(root, now); err != nil {
		return err
	}
	if err = seedEmailSettings(root, now); err != nil {
		return err
	}
	eventItems, err := seedEvents(root, now)
	if err != nil {
		return err
	}
	if err = seedAlerts(root, now); err != nil {
		return err
	}
	rules, err := seedMonitoring(root, now, eventItems)
	if err != nil {
		return err
	}
	return seedExecutions(root, now, rules, eventItems)
}

func initialDataIsEmpty(root string) (bool, error) {
	entries, err := os.ReadDir(filepath.Join(root, "senders"))
	if err == nil && len(entries) > 0 {
		return false, nil
	}
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return false, err
	}
	for _, path := range []string{"executions/executions.jsonl", "monitoring-executions.jsonl"} {
		info, statErr := os.Stat(filepath.Join(root, path))
		if statErr == nil && info.Size() > 0 {
			return false, nil
		}
		if statErr != nil && !errors.Is(statErr, os.ErrNotExist) {
			return false, statErr
		}
	}
	for path, collection := range map[string]string{"alerts.json": "items", "events.json": "events", "monitoring-rules.json": "rules"} {
		data, readErr := os.ReadFile(filepath.Join(root, path))
		if errors.Is(readErr, os.ErrNotExist) {
			continue
		}
		if readErr != nil {
			return false, readErr
		}
		var value map[string]json.RawMessage
		if json.Unmarshal(data, &value) != nil {
			return false, nil
		}
		var items []json.RawMessage
		if json.Unmarshal(value[collection], &items) != nil || len(items) > 0 {
			return false, nil
		}
	}
	return true, nil
}

